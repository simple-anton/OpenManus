"""Сжатие памяти исполнителя между шагами плана и внутри шага.

Что показал разбор прогона. Средний вход одного шага — 146 тысяч токенов,
максимальный 160 тысяч, и так все 37 шагов подряд. Причина простая: один и
тот же исполнитель проходит весь план, память ограничена сотней сообщений,
и к третьему шагу она забита до потолка. Дальше каждый шаг заново отправляет
модели эти сто сообщений — почти все они пересказ страниц, прочитанных час
назад и давно выписанных в журнал находок.

Именно на этом кончились токены: 5,4 млн на входе за неполный план.

Раз журнал находок теперь хранит всё важное на диске, держать в разговоре
сырые выдачи инструментов больше незачем. Здесь две меры:

* между пунктами плана память очищается полностью — новый пункт всё равно
  получает журнал и сводку предыдущих шагов в своей постановке задачи;
* внутри длинного пункта старые ответы инструментов заменяются заглушкой.

Вторая мера трогает только текст ответа, но не сами сообщения: у вызова
инструмента и его результата парная связь, и если удалить одно из пары,
модель откажется отвечать с ошибкой про несопоставленный tool_call.
"""

from typing import Any, List

from app.logger import logger


# Сколько последних обменов оставить нетронутыми внутри одного пункта плана.
# Свежие ответы инструментов агенту нужны дословно: он с ними работает прямо
# сейчас. Всё, что старше, он уже успел выписать в журнал.
KEEP_VERBATIM = 12

# Ниже этого размера ответ инструмента не трогаем: заглушка займёт столько же.
MIN_SQUASH = 600

STUB = (
    "[…содержимое свёрнуто, чтобы освободить место в разговоре. "
    "Если эти данные ещё нужны — они выписаны в журнал находок "
    "(findings.md) либо запросите источник заново.]"
)


def forget_previous_step(agent: Any) -> int:
    """Очищает память исполнителя перед новым пунктом плана.

    Возвращает, сколько сообщений выброшено — чтобы это было видно в логе.
    """
    memory = getattr(agent, "memory", None)
    if memory is None:
        return 0
    dropped = len(memory.messages)
    if dropped:
        memory.clear()
        logger.info(
            f"Память исполнителя очищена перед новым пунктом плана: "
            f"снято {dropped} сообщений. Контекст приходит из журнала находок."
        )
    return dropped


def squash_old_observations(
    agent: Any, keep: int = KEEP_VERBATIM, min_size: int = MIN_SQUASH
) -> int:
    """Сворачивает старые ответы инструментов внутри текущего пункта плана.

    Возвращает число освобождённых знаков.
    """
    memory = getattr(agent, "memory", None)
    if memory is None:
        return 0
    messages: List[Any] = memory.messages
    if len(messages) <= keep:
        return 0

    freed = 0
    for message in messages[:-keep]:
        # только ответы инструментов: реплики модели и постановка задачи нужны
        if message.role != "tool" or not message.content:
            continue
        if len(message.content) < min_size or message.content == STUB:
            continue
        freed += len(message.content) - len(STUB)
        message.content = STUB
        # картинки в старых сообщениях тем более незачем возить с собой
        message.base64_image = None
    if freed:
        logger.info(f"Свёрнуто старых ответов инструментов на {freed} знаков")
    return freed
