"""Своя вкладка браузера у каждой задачи.

Что произошло. Chromium в контейнере один, и все задачи подключаются к нему
через один и тот же протокол отладки. Вкладки у него общие, а «текущая
вкладка» — состояние всего браузера, не задачи. Пока одна задача исследовала
рынок аренды, вторая открыла ВКонтакте, и её же следующий вызов прочитал не
свою страницу. Из лога, дословно, рассуждение агента:

    «Странно: заголовок „VK | Welcome!", но текст на странице — объявления
     об аренде квартир в Ереване»
    «в браузере несколько вкладок, и „текущей" осталась вкладка List.am из
     прошлой сессии»

Заметить такое агент может только по несовпадению смысла — и то если
повезёт. Молча подмешанные чужие данные в отчёт куда опаснее.

Как чиним. Каждая задача владеет своей вкладкой. Перед её кодом мы
переключаемся на эту вкладку (а если её ещё нет — заводим), после кода
запоминаем, где задача оказалась. Соседняя задача переключает браузер на
свою вкладку так же, и на чужую страницу уже не попадает.

Общими остаются cookies и входы — это нарочно: вход, сделанный руками через
окно живого вида, должен работать во всех задачах.

Служебные строки в конце вырезаются из вывода: агенту их видеть незачем.
"""

import re
from typing import Optional, Tuple


# Метка, которой код в браузере сообщает нам, на какой вкладке он закончил.
MARKER = "__OM_TAB__="
_MARKER_LINE = re.compile(r"^\s*" + re.escape(MARKER) + r"(\S*)\s*$", re.MULTILINE)


def wrap(code: str, tab: Optional[str]) -> str:
    """Обрамляет код агента переключением на свою вкладку и запоминанием её.

    Пользуемся только теми помощниками, которые видны в рабочих логах:
    list_tabs(), switch_tab(), new_tab(), page_info(). Ничего не выдумываем —
    неизвестный вызов сломал бы каждый шаг с браузером.
    """
    mine = tab or ""
    head = (
        "__om_ids = [ (t.get('targetId') or t.get('target_id')) for t in list_tabs() ]\n"
        f"__om_mine = {mine!r}\n"
        "if __om_mine and __om_mine in __om_ids:\n"
        "    switch_tab(__om_mine)\n"
        "else:\n"
        "    new_tab('about:blank')\n"
    )
    # Хвост не должен ронять работу агента: если помощники поведут себя иначе,
    # мы просто не обновим метку, а шаг всё равно отработает.
    tail = (
        "\ntry:\n"
        "    __om_now = page_info().get('url')\n"
        "    __om_hit = [ (t.get('targetId') or t.get('target_id'))\n"
        "                 for t in list_tabs() if t.get('url') == __om_now ]\n"
        "    if len(__om_hit) == 1:\n"
        f"        print({MARKER!r} + str(__om_hit[0]))\n"
        "except Exception:\n"
        "    pass\n"
    )
    return head + "\n" + (code or "") + tail


def switch_only(tab: Optional[str]) -> str:
    """Код, который лишь ставит текущей нашу вкладку.

    Нужен перед снимком экрана: у browser_screenshot нет параметра с кодом,
    а снимает он текущую вкладку — то есть, без этого, возможно чужую.
    """
    return wrap("", tab)


def take_tab(output: str) -> Tuple[str, Optional[str]]:
    """Вынимает метку вкладки из вывода и убирает её с глаз агента."""
    found = None
    for match in _MARKER_LINE.finditer(output or ""):
        found = match.group(1) or None
    if found is None and MARKER not in (output or ""):
        return output, None
    cleaned = _MARKER_LINE.sub("", output or "")
    # после вырезания строки остаётся лишний перевод — схлопываем
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned).strip("\n")
    return cleaned, found
